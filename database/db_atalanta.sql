-- ==========================================
--   TABLA TICKETS
-- ==========================================
CREATE TABLE TICKETS(
    ID_TICKET INT AUTO_INCREMENT,
    STATUS VARCHAR(20) DEFAULT 'CREATED',
    TITLE VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(500) NOT NULL,
    CREATION_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    
    ID_CLIENT INT NOT NULL,
	ROLE_CLIENT VARCHAR(20) DEFAULT 'CLIENT',
	
    CONSTRAINT CK_ROLE_CLIENT CHECK (ROLE_CLIENT IN ('CLIENT')),
	CONSTRAINT CK_STATUS CHECK (STATUS IN('CREATED')),
	
	CONSTRAINT PK_ID_TICKET PRIMARY KEY(ID_TICKET),
	CONSTRAINT FK_ID_CLIENT_ROLE_CLIENT FOREIGN KEY (ID_CLIENT,ROLE_CLIENT)
		REFERENCES USERS (ID_USER, ROLE) ON DELETE CASCADE
);
